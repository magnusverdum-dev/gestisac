import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = parseArgs(process.argv.slice(2));
const defaultSource = process.env.GESTISAC_DATA_PATH || path.join(rootDir, 'apps/api/data/store.json');
const sourcePath = path.resolve(args.source || defaultSource);
const outPath = args.out ? path.resolve(args.out) : '';

if (!existsSync(sourcePath)) {
  fail(`JSON store not found at ${sourcePath}. Pass --source <store.json>.`);
}

const store = JSON.parse(readFileSync(sourcePath, 'utf8'));
const plan = buildSeedPlan(store, sourcePath);
const sql = `${plan.statements.join('\n')}\n`;

if (outPath) {
  mkdirSync(path.dirname(outPath), { recursive: true });
  writeFileSync(outPath, sql);
  console.log(`Seed SQL written: ${outPath}`);
} else {
  process.stdout.write(sql);
}

if (plan.warnings.length) {
  for (const warning of plan.warnings) {
    console.warn(`Warning: ${warning}`);
  }
}

function parseArgs(items) {
  const parsed = {};
  for (let index = 0; index < items.length; index += 1) {
    const item = items[index];
    if (!item.startsWith('--')) continue;
    const key = item.slice(2);
    const next = items[index + 1];
    if (!next || next.startsWith('--')) {
      parsed[key] = true;
    } else {
      parsed[key] = next;
      index += 1;
    }
  }
  return parsed;
}

function buildSeedPlan(store, source) {
  const warnings = [];
  const tenantId = firstTenantId(store);
  const condominiums = array(store.condominiums);
  const condominiumLookup = buildCondominiumLookup(condominiums);
  const buildingLookup = buildBuildingLookup(array(store.buildings), condominiumLookup, warnings);
  const fractionLookup = buildFractionLookup(array(store.fractions), condominiumLookup, warnings);
  const statements = [
    '-- Generated by scripts/build-postgres-snapshot-seed.mjs',
    `-- Source: ${source.replaceAll('\\', '/')}`,
    '-- Intended for an empty/staging PostgreSQL database after the GESTISAC schema exists.',
    'BEGIN;'
  ];

  seedIdentity(statements, store, tenantId);
  seedCondominiums(statements, store, tenantId);
  seedOcorrencias(statements, store, tenantId);
  seedOperational(statements, store, tenantId);
  seedDocumental(statements, store, tenantId);
  seedFinancial(statements, store, tenantId);
  seedAccountingContext(statements, store, tenantId);
  seedChat(statements, store, tenantId);
  seedRelationalCore(statements, store, tenantId, condominiumLookup, buildingLookup, fractionLookup, warnings);

  statements.push('COMMIT;');
  return { statements, warnings };
}

