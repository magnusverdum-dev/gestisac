function seedRelationalCore(
  statements,
  store,
  tenantId,
  condominiumLookup,
  buildingLookup,
  fractionLookup,
  warnings
) {
  for (const tenant of ensureTenants(store, tenantId)) {
    statements.push(
      insertStatement('tenants', {
        id: tenant.id,
        name: tenant.name,
        slug: tenant.slug || tenant.id,
        status: tenant.status || 'active',
        metadata: jsonb(tenant)
      })
    );
  }

  for (const user of array(store.users)) {
    statements.push(
      insertStatement('users', {
        id: user.id,
        tenant_id: user.tenantId || user.tenant_id || tenantId,
        name: user.name || '',
        email: user.email || '',
        role: user.role || '',
        password_hash: user.passwordHash || user.password_hash || '',
        active_condominium_id: user.activeCondominium || user.active_condominium || '',
        metadata: jsonb(safeUserMetadata(user))
      })
    );
  }

  for (const condominium of array(store.condominiums)) {
    statements.push(
      insertStatement('condominiums', {
        id: condominium.id,
        tenant_id: tenantId,
        name: condominium.name || '',
        internal_code: condominium.internalCode || condominium.internal_code || '',
        external_reference: condominium.externalReference || condominium.external_reference || '',
        status: condominium.status || '',
        location: condominium.location || '',
        metadata: jsonb(condominium)
      })
    );
  }

  for (const building of array(store.buildings)) {
    const condominiumId = lookupCondominiumId(building.condominium, condominiumLookup);
    if (!condominiumId) {
      warnings.push(`Skipped building ${building.id}: condominium not found (${building.condominium}).`);
      continue;
    }
    statements.push(
      insertStatement('buildings', {
        id: building.id,
        tenant_id: tenantId,
        condominium_id: condominiumId,
        name: building.name || '',
        metadata: jsonb(building)
      })
    );
  }

  for (const fraction of array(store.fractions)) {
    const condominiumId = lookupCondominiumId(fraction.condominium, condominiumLookup);
    if (!condominiumId) {
      warnings.push(`Skipped fraction ${fraction.id}: condominium not found (${fraction.condominium}).`);
      continue;
    }
    statements.push(
      insertStatement('fractions', {
        id: fraction.id,
        tenant_id: tenantId,
        condominium_id: condominiumId,
        building_id: buildingLookup.get(`${condominiumId}::${normalizeLookupKey(fraction.building)}`) || null,
        code: fraction.number || '',
        floor: fraction.floor || '',
        metadata: jsonb(fraction)
      })
    );
  }

  for (const resident of array(store.residents)) {
    const condominiumId = lookupCondominiumId(resident.condominium, condominiumLookup);
    if (!condominiumId) {
      warnings.push(`Skipped resident ${resident.id}: condominium not found (${resident.condominium}).`);
      continue;
    }
    statements.push(
      insertStatement('residents', {
        id: resident.id,
        tenant_id: tenantId,
        condominium_id: condominiumId,
        fraction_id: fractionLookup.get(`${condominiumId}::${normalizeLookupKey(resident.fraction)}`) || null,
        name: resident.name || '',
        email: resident.email || '',
        phone: resident.phone || '',
        role: resident.status || '',
        metadata: jsonb(resident)
      })
    );
  }
}

function insertStatement(table, row) {
  const entries = Object.entries(row).filter(([, value]) => value !== undefined);
  const columns = entries.map(([key]) => key).join(', ');
  const values = entries.map(([, value]) => sqlValue(value)).join(', ');
  const updates = entries
    .filter(([key]) => key !== 'id')
    .map(([key]) => `${key} = EXCLUDED.${key}`)
    .join(', ');
  return `INSERT INTO ${table} (${columns}) VALUES (${values}) ON CONFLICT (id) DO UPDATE SET ${updates};`;
}

function buildCondominiumLookup(condominiums) {
  const lookup = new Map();
  for (const condominium of condominiums) {
    const keys = [
      condominium.id,
      condominium.name,
      condominium.internalCode || condominium.internal_code,
      condominium.externalReference || condominium.external_reference
    ];
    for (const key of keys) {
      const normalized = normalizeLookupKey(key);
      if (normalized && !lookup.has(normalized)) {
        lookup.set(normalized, condominium.id);
      }
    }
  }
  return lookup;
}

function buildBuildingLookup(buildings, condominiumLookup, warnings) {
  const lookup = new Map();
  for (const building of buildings) {
    const condominiumId = lookupCondominiumId(building.condominium, condominiumLookup);
    if (!condominiumId) {
      warnings.push(`Could not index building ${building.id}: condominium not found (${building.condominium}).`);
      continue;
    }
    const key = `${condominiumId}::${normalizeLookupKey(building.name)}`;
    if (key && !lookup.has(key)) lookup.set(key, building.id);
  }
  return lookup;
}

function buildFractionLookup(fractions, condominiumLookup, warnings) {
  const lookup = new Map();
  for (const fraction of fractions) {
    const condominiumId = lookupCondominiumId(fraction.condominium, condominiumLookup);
    if (!condominiumId) {
      warnings.push(`Could not index fraction ${fraction.id}: condominium not found (${fraction.condominium}).`);
      continue;
    }
    const key = `${condominiumId}::${normalizeLookupKey(fraction.number)}`;
    if (key && !lookup.has(key)) lookup.set(key, fraction.id);
  }
  return lookup;
}

function lookupCondominiumId(value, lookup) {
  return lookup.get(normalizeLookupKey(value)) || '';
}

function sqlValue(value) {
  if (value && value.__raw) return value.sql;
  if (value === null) return 'NULL';
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : '0';
  if (typeof value === 'boolean') return value ? 'TRUE' : 'FALSE';
  if (value && value.__jsonb) return `${quote(JSON.stringify(value.value))}::jsonb`;
  return quote(String(value ?? ''));
}

function quote(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function jsonb(value) {
  return { __jsonb: true, value };
}

function safeUserMetadata(user) {
  const metadata = { ...user };
  delete metadata.passwordHash;
  delete metadata.password_hash;
  return metadata;
}

function timestamp(value) {
  return nullableTimestamp(value) || raw('now()');
}

function nullableTimestamp(value) {
  if (!value) return null;
  const parsed = new Date(value);
  return Number.isNaN(parsed.getTime()) ? null : parsed.toISOString();
}

function raw(sql) {
  return { __raw: true, sql };
}

function firstTenantId(store) {
  return (
    array(store.tenants)[0]?.id ||
    array(store.users)[0]?.tenantId ||
    array(store.users)[0]?.tenant_id ||
    'tenant-gestisac'
  );
}

function ensureTenants(store, tenantId) {
  const tenants = array(store.tenants);
  if (tenants.length) return tenants;
  return [{ id: tenantId, name: 'GESTISAC', slug: 'gestisac', status: 'active' }];
}

function normalizeLookupKey(value) {
  const text = String(value || '').trim();
  if (!text) return '';
  return text
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}

function array(value) {
  return Array.isArray(value) ? value : [];
}

function fail(message) {
  console.error(message);
  process.exit(1);
}
