import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = parseArgs(process.argv.slice(2));
const defaultSource = process.env.GESTISAC_DATA_PATH || path.join(rootDir, 'apps/api/data/store.json');
const sourcePath = path.resolve(args.source || defaultSource);
const outDir = path.resolve(args.out || path.join(rootDir, '.codex-logs/postgres-migration'));

if (args['restore-backup']) {
  restoreBackup(path.resolve(args['restore-backup']), sourcePath);
  process.exit(0);
}

if (!existsSync(sourcePath)) {
  fail(
    `JSON store not found at ${sourcePath}. Start the API once or pass --source <store.json>.`
  );
}

mkdirSync(outDir, { recursive: true });

const timestamp = new Date().toISOString().replace(/[:.]/g, '-');
const backupPath = path.join(outDir, `store.backup.${timestamp}.json`);
copyFileSync(sourcePath, backupPath);

const store = JSON.parse(readFileSync(sourcePath, 'utf8'));
const report = buildReport(store, sourcePath, backupPath);
const reportPath = path.join(outDir, `migration-report.${timestamp}.json`);
writeFileSync(reportPath, `${JSON.stringify(report, null, 2)}\n`);

let sqlPath = '';
if (args['write-sql']) {
  sqlPath = path.join(outDir, `migration-plan.${timestamp}.sql`);
  writeFileSync(sqlPath, buildSqlPlan(store));
}

console.log(`Dry-run complete: ${reportPath}`);
console.log(`Backup created: ${backupPath}`);
if (sqlPath) {
  console.log(`SQL plan written: ${sqlPath}`);
} else {
  console.log('No SQL written. Pass --write-sql to generate a staged import plan.');
}

function parseArgs(items) {
  const parsed = {};
  for (let index = 0; index < items.length; index += 1) {
    const item = items[index];
    if (!item.startsWith('--')) continue;
    const key = item.slice(2);
    const next = items[index + 1];
    if (!next || next.startsWith('--')) {
      parsed[key] = true;
    } else {
      parsed[key] = next;
      index += 1;
    }
  }
  return parsed;
}

function restoreBackup(backupPath, destinationPath) {
  if (!existsSync(backupPath)) {
    fail(`Backup not found at ${backupPath}`);
  }
  mkdirSync(path.dirname(destinationPath), { recursive: true });
  copyFileSync(backupPath, destinationPath);
  console.log(`Restored ${backupPath} to ${destinationPath}`);
}

function buildReport(store, source, backup) {
  const collections = {
    tenants: store.tenants,
    users: store.users,
    condominiums: store.condominiums,
    buildings: store.buildings,
    fractions: store.fractions,
    residents: store.residents,
    suppliers: store.suppliers,
    ocorrencias: store.ocorrencias,
    ocorrenciaComentarios: store.ocorrenciaComentarios,
    ocorrenciaAnexos: store.ocorrenciaAnexos,
    quotas: store.quotas,
    accountingPayments: store.accountingPayments,
    debts: store.debts,
    receipts: store.receipts,
    expenses: store.expenses,
    paymentAgreements: store.paymentAgreements,
    cashMovements: store.cashMovements,
    bankTransactions: store.bankTransactions,
    bankReconciliations: store.bankReconciliations,
    documents: store.documents,
    maintenance: store.maintenance,
    inspections: store.inspections,
    calendarEvents: store.calendarEvents,
    auditLog: store.auditLog
  };

  const counts = {};
  const checksums = {};
  for (const [name, value] of Object.entries(collections)) {
    const collection = Array.isArray(value) ? value : [];
    counts[name] = collection.length;
    checksums[name] = sha256(stableStringify(collection));
  }

  const warnings = [];
  if (!counts.tenants) warnings.push('No tenants found; import will create/use the demo tenant fallback.');
  if (!counts.users) warnings.push('No users found; login must be recreated before production cutover.');
  if (!counts.condominiums) warnings.push('No condominiums found; relational import would be empty.');

  return {
    mode: args['write-sql'] ? 'dry-run-with-sql-plan' : 'dry-run',
    generatedAt: new Date().toISOString(),
    source,
    backup,
    target: 'PostgreSQL relational schema 202606010010_init_relational_core.sql',
    counts,
    checksums,
    warnings,
    rollback: {
      command: `node scripts/migrate-json-to-postgres.mjs --restore-backup "${backup}"`
    }
  };
}

function buildSqlPlan(store) {
  const tenantId = firstTenantId(store);
  const statements = [
    '-- Generated by scripts/migrate-json-to-postgres.mjs',
    '-- Review before running. Execute inside a transaction on an empty/staging database first.',
    'BEGIN;'
  ];

  for (const tenant of ensureTenants(store)) {
    statements.push(
      insertStatement('tenants', {
        id: tenant.id,
        name: tenant.name,
        slug: tenant.slug || tenant.id,
        status: tenant.status || 'active',
        metadata: jsonb(tenant)
      })
    );
  }

  for (const user of array(store.users)) {
    statements.push(
      insertStatement('users', {
        id: user.id,
        tenant_id: user.tenantId || user.tenant_id || tenantId,
        name: user.name,
        email: user.email,
        role: user.role || '',
        password_hash: user.passwordHash || user.password_hash || '',
        active_condominium_id: user.activeCondominium || user.active_condominium || '',
        metadata: jsonb(user)
      })
    );
  }

  for (const condominium of array(store.condominiums)) {
    statements.push(
      insertStatement('condominiums', {
        id: condominium.id,
        tenant_id: tenantId,
        name: condominium.name,
        internal_code: condominium.internalCode || condominium.internal_code || '',
        external_reference: condominium.externalReference || condominium.external_reference || '',
        status: condominium.status || '',
        location: condominium.location || '',
        metadata: jsonb(condominium)
      })
    );
  }

  for (const ticket of array(store.ocorrencias)) {
    statements.push(
      insertStatement('tickets', {
        id: ticket.id,
        tenant_id: tenantId,
        condominium_id: emptyToNull(ticket.condominiumId || ticket.condominium_id),
        title: ticket.titulo || ticket.title || 'Ticket sem titulo',
        description: ticket.descricao || ticket.description || '',
        category: ticket.categoria || ticket.category || '',
        type: ticket.tipo || ticket.type || 'pedido',
        status: ticket.status || 'nova',
        priority: ticket.prioridade || ticket.priority || 'normal',
        impact: ticket.impacto || ticket.impact || 'medio',
        urgency: ticket.urgencia || ticket.urgency || 'media',
        origin_channel: ticket.originChannel || ticket.origin_channel || 'hq',
        requester_name: ticket.requisitanteNome || ticket.requisitante_nome || '',
        requester_email: ticket.requisitanteEmail || ticket.requisitante_email || '',
        requester_phone: ticket.requisitanteTelefone || ticket.requisitante_telefone || '',
        public_status_text: ticket.publicStatusText || ticket.public_status_text || '',
        public_timeline_status: ticket.publicTimelineStatus || ticket.public_timeline_status || '',
        technical_notes: ticket.technicalNotes || ticket.technical_notes || '',
        hq_validation_status: ticket.hqValidationStatus || ticket.hq_validation_status || 'nao_requerida',
        hq_validation_notes: ticket.hqValidationNotes || ticket.hq_validation_notes || '',
        metadata: jsonb(ticket)
      })
    );
  }

  statements.push(
    '-- Accounting tables are created by the relational migration. Map quotas/payments/debts in staging before production cutover.'
  );
  statements.push('COMMIT;');
  return `${statements.join('\n')}\n`;
}

function insertStatement(table, row) {
  const entries = Object.entries(row).filter(([, value]) => value !== undefined);
  const columns = entries.map(([key]) => key).join(', ');
  const values = entries.map(([, value]) => sqlValue(value)).join(', ');
  const updates = entries
    .filter(([key]) => key !== 'id')
    .map(([key]) => `${key} = EXCLUDED.${key}`)
    .join(', ');
  return `INSERT INTO ${table} (${columns}) VALUES (${values}) ON CONFLICT (id) DO UPDATE SET ${updates};`;
}

function sqlValue(value) {
  if (value === null) return 'NULL';
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : '0';
  if (typeof value === 'boolean') return value ? 'TRUE' : 'FALSE';
  if (value && value.__jsonb) return `${quote(JSON.stringify(value.value))}::jsonb`;
  return quote(String(value ?? ''));
}

function quote(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function jsonb(value) {
  return { __jsonb: true, value };
}

function emptyToNull(value) {
  const text = String(value || '').trim();
  return text ? text : null;
}

function firstTenantId(store) {
  return array(store.tenants)[0]?.id || array(store.users)[0]?.tenantId || array(store.users)[0]?.tenant_id || 'demo';
}

function ensureTenants(store) {
  const tenants = array(store.tenants);
  if (tenants.length) return tenants;
  return [{ id: firstTenantId(store), name: 'Demo', slug: 'demo', status: 'active' }];
}

function array(value) {
  return Array.isArray(value) ? value : [];
}

function stableStringify(value) {
  if (Array.isArray(value)) return `[${value.map(stableStringify).join(',')}]`;
  if (value && typeof value === 'object') {
    return `{${Object.keys(value)
      .sort()
      .map((key) => `${JSON.stringify(key)}:${stableStringify(value[key])}`)
      .join(',')}}`;
  }
  return JSON.stringify(value);
}

function sha256(value) {
  return createHash('sha256').update(value).digest('hex');
}

function fail(message) {
  console.error(message);
  process.exit(1);
}
